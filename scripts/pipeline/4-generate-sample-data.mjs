#!/usr/bin/env node
/**
 * Generate sampleData.ts and update store.ts TTB_LABEL_IMAGES
 * from real TTB COLA records + downloaded label images.
 *
 * Usage: node generate-sample-data.mjs
 */

import { readFileSync, writeFileSync, readdirSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const ROOT = join(__dirname, '..', '..');
const RECORDS_PATH = join(ROOT, 'sample_labels', 'ttb_cola_records.json');
const ENRICHED_PATH = join(ROOT, 'sample_labels', 'enriched_cola_fields.json');
const IMAGES_DIR = join(ROOT, 'frontend', 'public', 'ttb-labels');
const SAMPLE_DATA_PATH = join(ROOT, 'frontend', 'src', 'lib', 'sampleData.ts');
const STORE_PATH = join(ROOT, 'frontend', 'src', 'lib', 'store.ts');

// ── 1. Scan images directory ────────────────────────────────────────────────
const imageFiles = readdirSync(IMAGES_DIR).filter(f => f.endsWith('.png'));
const imageMap = {}; // ttbId → [1, 2, 3, ...]
for (const f of imageFiles) {
  const match = f.match(/^(\d+)-(\d+)\.png$/);
  if (!match) continue;
  const [, ttbId, num] = match;
  if (!imageMap[ttbId]) imageMap[ttbId] = [];
  imageMap[ttbId].push(parseInt(num));
}
for (const id of Object.keys(imageMap)) {
  imageMap[id].sort((a, b) => a - b);
}

console.log(`📸 ${Object.keys(imageMap).length} TTB IDs with images (${imageFiles.length} total files)`);

// ── 2. Load records and enriched COLA fields, filter to those with images ────
const allRecords = JSON.parse(readFileSync(RECORDS_PATH, 'utf-8'));
let enriched = {};
try { enriched = JSON.parse(readFileSync(ENRICHED_PATH, 'utf-8')); } catch { /* no enriched data */ }
console.log(`📋 ${Object.keys(enriched).length} enriched COLA records loaded`);

const records = [];
for (const cat of ['beer', 'wine', 'spirits']) {
  for (const r of (allRecords[cat] || [])) {
    if (imageMap[r.ttbId]) {
      // Merge enriched COLA detail page data into the record
      const e = enriched[r.ttbId] || {};
      records.push({
        ...r,
        category: cat,
        // Use enriched fields as ground truth (scraped from COLA detail page)
        classType: e.classTypeCode || r.classType || '',
        origin: e.originCode || r.origin || '',
        grapeVarietal: (e.grapeVarietal && e.grapeVarietal !== 'N/A') ? e.grapeVarietal : '',
        wineAppellation: e.wineAppellation || '',
        brandName: e.brandName || r.brandName || '',
        fancifulName: e.fancifulName || r.fancifulName || '',
        // Vision-extracted fields (from Gemini label image analysis)
        visionAlcohol: e.alcoholContent || null,
        visionNetContents: e.netContents || null,
      });
    }
  }
}
console.log(`📋 ${records.length} records with images`);

// ── 3. Category-aware defaults ──────────────────────────────────────────────
function classifyFromType(classType) {
  if (!classType) return 'spirits';
  const ct = classType.toUpperCase();
  const beerTerms = ['ALE', 'LAGER', 'STOUT', 'PORTER', 'IPA', 'PILSNER', 'MALT', 'BEER', 'SAISON', 'WHEAT', 'CIDER', 'SELTZER', 'TEA'];
  const wineTerms = ['WINE', 'CABERNET', 'CHARDONNAY', 'MERLOT', 'PINOT', 'SAUVIGNON', 'RIESLING', 'ZINFANDEL', 'SYRAH', 'MALBEC', 'VIOGNIER', 'ROSE', 'CHAMPAGNE', 'PROSECCO', 'SPARKLING', 'MOSCATO', 'PORT', 'SHERRY', 'BLEND', 'GRIGIO', 'NERO'];
  for (const t of beerTerms) if (ct.includes(t)) return 'beer';
  for (const t of wineTerms) if (ct.includes(t)) return 'wine';
  return 'spirits';
}

function defaultAlcohol(category, classType) {
  const ct = (classType || '').toUpperCase();
  if (ct.includes('NON-ALCOHOLIC') || ct.includes('NEAR BEER')) return 'Less than 0.5% Alc. By Vol.';
  if (category === 'beer') return '5.5% Alc. By Vol.';
  if (category === 'wine') return 'Alcohol 13.5% by Volume';
  return '40% Alc./Vol. (80 Proof)';
}

function defaultNetContents(category) {
  if (category === 'beer') return '12 FL OZ (355 mL)';
  return '750 mL';
}

function slugify(brand, fanciful) {
  const parts = [brand, fanciful].filter(Boolean).join(' ');
  return parts.toLowerCase()
    .replace(/['']/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 50);
}

function titleCase(s) {
  return s.toLowerCase().replace(/\b\w/g, c => c.toUpperCase());
}

/** Escape a value for safe embedding in a TS string literal */
function esc(s) {
  return (s || '').replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, ' ').replace(/\r/g, '');
}

// ── 4. Generate sampleData.ts ───────────────────────────────────────────────
let ts = `/**
 * Sample label data derived from real TTB COLA records.
 * AUTO-GENERATED by scripts/generate-sample-data.mjs — do not edit manually.
 */

// ---------------------------------------------------------------------------
// Types
// ---------------------------------------------------------------------------

export interface ColaSource {
  ttbId: string;
  brand: string;
  fancifulName: string;
  classCode: string;
  classType: string;
  originCode: string;
  origin: string;
  permit: string;
  approved: string;
}

export interface LabelGeneration {
  labelType: "front" | "back";
  category: "beer" | "wine" | "spirits";
  brandName: string;
  classType: string;
  alcoholContent: string;
  netContents: string;
  appellation?: string;
  vintage?: string;
  nameAddress?: string;
  countryOfOrigin?: string;
}

export interface ExpectedFields {
  brand_name: string;
  class_type: string;
  alcohol_content?: string;
  net_contents: string;
  health_warning?: string;
  name_address?: string;
  country_origin?: string;
  sulfite_declaration?: string;
  appellation?: string;
  vintage_date?: string;
  varietal?: string;
  age_statement?: string;
  color_ingredients?: string;
  commodity_statement?: string;
  aspartame_declaration?: string;
}

export interface SampleLabel {
  key: string;
  displayName: string;
  colaSource: ColaSource;
  generation: LabelGeneration;
  expectedFields: ExpectedFields;
}

// ---------------------------------------------------------------------------
// Health warning constant
// ---------------------------------------------------------------------------

export const GOV_WARNING =
  "GOVERNMENT WARNING: (1) According to the Surgeon General, women should not drink alcoholic beverages during pregnancy because of the risk of birth defects. (2) Consumption of alcoholic beverages impairs your ability to drive a car or operate machinery, and may cause health problems.";

`;

// Group by category
const byCategory = { beer: [], wine: [], spirits: [] };
for (const r of records) {
  const cat = r.category || classifyFromType(r.classType);
  byCategory[cat].push(r);
}

// Generate entries for each category
for (const [cat, catRecords] of Object.entries(byCategory)) {
  const varName = cat.toUpperCase() + '_SAMPLES';
  ts += `// ---------------------------------------------------------------------------\n`;
  ts += `// ${titleCase(cat)} samples\n`;
  ts += `// ---------------------------------------------------------------------------\n\n`;
  ts += `const ${varName}: SampleLabel[] = [\n`;

  for (const r of catRecords) {
    const slug = slugify(r.brandName, r.fancifulName);
    const displayBrand = titleCase(r.brandName);
    const displayFanciful = r.fancifulName ? titleCase(r.fancifulName) : '';
    const displayName = displayFanciful ? `${displayBrand} ${displayFanciful}` : displayBrand;
    const classType = r.classType || (cat === 'beer' ? 'Ale' : cat === 'wine' ? 'Wine' : 'Spirits');
    // Use vision-extracted values when available, fall back to defaults
    const alc = r.visionAlcohol || defaultAlcohol(cat, classType);
    const net = r.visionNetContents || defaultNetContents(cat);
    const origin = r.origin || '';

    // Front label
    ts += `  {\n`;
    ts += `    key: "${slug}-front",\n`;
    ts += `    displayName: "${esc(displayName)} (Front)",\n`;
    ts += `    colaSource: {\n`;
    ts += `      ttbId: "${r.ttbId}",\n`;
    ts += `      brand: "${esc(r.brandName)}",\n`;
    ts += `      fancifulName: "${esc(r.fancifulName)}",\n`;
    ts += `      classCode: "",\n`;
    ts += `      classType: "${esc(classType)}",\n`;
    ts += `      originCode: "",\n`;
    ts += `      origin: "${esc(origin)}",\n`;
    ts += `      permit: "",\n`;
    ts += `      approved: "${r.approvalDate || r.completedDate || ''}",\n`;
    ts += `    },\n`;
    ts += `    generation: {\n`;
    ts += `      labelType: "front",\n`;
    ts += `      category: "${cat}",\n`;
    ts += `      brandName: "${esc(r.brandName)}",\n`;
    ts += `      classType: "${esc(titleCase(classType))}",\n`;
    ts += `      alcoholContent: "${esc(alc)}",\n`;
    ts += `      netContents: "${esc(net)}",\n`;
    if (origin && cat !== 'beer') {
      ts += `      countryOfOrigin: "${esc(origin)}",\n`;
    }
    ts += `    },\n`;
    ts += `    expectedFields: {\n`;
    ts += `      brand_name: "${esc(r.brandName)}",\n`;
    ts += `      class_type: "${esc(titleCase(classType))}",\n`;
    ts += `      alcohol_content: "${esc(alc)}",\n`;
    ts += `      net_contents: "${esc(net)}",\n`;
    // Add varietal from enriched COLA data (ground truth from submitted form)
    if (r.grapeVarietal) {
      ts += `      varietal: "${esc(r.grapeVarietal)}",\n`;
    }
    // Add appellation from enriched COLA data
    if (r.wineAppellation) {
      ts += `      appellation: "${esc(r.wineAppellation)}",\n`;
    }
    ts += `    },\n`;
    ts += `  },\n`;
  }

  ts += `];\n\n`;
}

// Combined exports + helper functions
ts += `// ---------------------------------------------------------------------------
// Combined exports
// ---------------------------------------------------------------------------

export const SAMPLE_LABELS: SampleLabel[] = [
  ...BEER_SAMPLES,
  ...WINE_SAMPLES,
  ...SPIRITS_SAMPLES,
];

export function getSampleLabel(key: string): SampleLabel | undefined {
  return SAMPLE_LABELS.find((s) => s.key === key);
}

export function getSamplesByCategory(category: "beer" | "wine" | "spirits"): SampleLabel[] {
  return SAMPLE_LABELS.filter((s) => s.generation.category === category);
}

export function getFrontSamples(): SampleLabel[] {
  return SAMPLE_LABELS.filter((s) => s.generation.labelType === "front");
}

export function toLabelParams(sample: SampleLabel) {
  return { ...sample.generation };
}

// ---------------------------------------------------------------------------
// Product pairs
// ---------------------------------------------------------------------------

const DEFAULT_NAME_ADDRESS: Record<string, string> = {
`;

// Generate name/address defaults
for (const r of records) {
  const brand = esc(r.brandName);
  const origin = r.origin || '';
  const addr = origin ? `${titleCase(brand)} Beverage Co., ${esc(titleCase(origin))}` : `${titleCase(brand)} Beverage Co.`;
  ts += `  "${brand}": "${esc(addr)}",\n`;
}

ts += `};

export interface SampleProduct {
  productKey: string;
  productName: string;
  category: "beer" | "wine" | "spirits";
  ttbId: string;
  front: LabelGeneration;
  back: LabelGeneration;
  expectedFrontFields: ExpectedFields;
  expectedBackFields: ExpectedFields;
}

export function getSampleProducts(): SampleProduct[] {
  const frontSamples = SAMPLE_LABELS.filter((s) => s.generation.labelType === "front");

  return frontSamples.map((front) => {
    const productKey = front.key.replace(/-front$/, "");
    const backKey = \`\${productKey}-back\`;
    const backSample = SAMPLE_LABELS.find((s) => s.key === backKey);

    const backGeneration: LabelGeneration = backSample
      ? backSample.generation
      : {
          labelType: "back",
          category: front.generation.category,
          brandName: front.generation.brandName,
          classType: front.generation.classType,
          alcoholContent: front.generation.alcoholContent,
          netContents: front.generation.netContents,
          nameAddress: DEFAULT_NAME_ADDRESS[front.generation.brandName] || \`\${front.generation.brandName} Beverage Co.\`,
          countryOfOrigin: front.generation.countryOfOrigin,
        };

    const backExpected: ExpectedFields = backSample
      ? backSample.expectedFields
      : {
          brand_name: front.expectedFields.brand_name,
          class_type: front.expectedFields.class_type,
          net_contents: front.expectedFields.net_contents,
          health_warning: GOV_WARNING,
          name_address: backGeneration.nameAddress || "",
          ...(backGeneration.countryOfOrigin ? { country_origin: backGeneration.countryOfOrigin } : {}),
          ...(front.generation.category === "wine" ? { sulfite_declaration: "Contains Sulfites" } : {}),
        };

    const displayName = front.displayName.replace(" (Front)", "");

    return {
      productKey,
      productName: displayName,
      category: front.generation.category,
      ttbId: front.colaSource.ttbId,
      front: front.generation,
      back: backGeneration,
      expectedFrontFields: front.expectedFields,
      expectedBackFields: backExpected,
    };
  });
}
`;

writeFileSync(SAMPLE_DATA_PATH, ts);
console.log(`✅ Generated ${SAMPLE_DATA_PATH}`);
console.log(`   ${byCategory.beer.length} beer + ${byCategory.wine.length} wine + ${byCategory.spirits.length} spirits = ${records.length} products`);

// ── 5. Generate TTB_LABEL_IMAGES for store.ts ───────────────────────────────
const imgLines = [];
for (const [ttbId, nums] of Object.entries(imageMap).sort()) {
  // Find the brand for this ID
  const rec = records.find(r => r.ttbId === ttbId);
  const comment = rec ? rec.brandName : '';
  imgLines.push(`  "${ttbId}": [${nums.join(', ')}],${comment ? `  // ${comment}` : ''}`);
}

const ttbBlock = `const TTB_LABEL_IMAGES: Record<string, number[]> = {\n${imgLines.join('\n')}\n};`;
console.log(`\n📝 TTB_LABEL_IMAGES block (${Object.keys(imageMap).length} entries):`);
console.log(ttbBlock);

// Write TTB_LABEL_IMAGES block to a temp file for easy copy
writeFileSync(join(ROOT, 'sample_labels', 'ttb_label_images_block.txt'), ttbBlock);
console.log(`\n💾 Block saved to sample_labels/ttb_label_images_block.txt`);

// ── 6. Generate store.ts overrides ──────────────────────────────────────────
// We need exactly `records.length` overrides. Create a realistic distribution:
// ~40% submitted (no OCR), ~15% in_review, ~20% approved, ~12% rejected, ~13% needs_revision
const overrides = [];
const statuses = [];
const total = records.length;
const nSubmitted = Math.round(total * 0.40);
const nInReview = Math.round(total * 0.15);
const nApproved = Math.round(total * 0.20);
const nRejected = Math.round(total * 0.12);
const nRevision = total - nSubmitted - nInReview - nApproved - nRejected;

for (let i = 0; i < nSubmitted; i++) statuses.push('submitted');
for (let i = 0; i < nInReview; i++) statuses.push('in_review');
for (let i = 0; i < nApproved; i++) statuses.push('approved');
for (let i = 0; i < nRejected; i++) statuses.push('rejected');
for (let i = 0; i < nRevision; i++) statuses.push('needs_revision');

// Shuffle deterministically
const shuffled = statuses.sort((a, b) => {
  const ha = [...a].reduce((h, c) => (h * 31 + c.charCodeAt(0)) & 0xFFFFFF, 0);
  const hb = [...b].reduce((h, c) => (h * 31 + c.charCodeAt(0)) & 0xFFFFFF, 0);
  return ha - hb;
});

console.log(`\n📊 Status distribution for ${total} products:`);
console.log(`   submitted: ${nSubmitted}, in_review: ${nInReview}, approved: ${nApproved}, rejected: ${nRejected}, needs_revision: ${nRevision}`);

// Reviewer pool
const reviewers = ['Jenny Park', 'Dave Morrison'];
const submitterSuffixes = { beer: 'Brewing Co.', wine: 'Wine Estates', spirits: 'Spirits Inc.' };

// Review findings templates
const findings = {
  rejected: [
    { id: 'country_origin', msg: 'Country of origin statement missing or not in English (27 CFR 4.39(a) / 5.63(b)).', sev: 'error' },
    { id: 'alcohol_content', msg: 'Alcohol content must be stated as percentage by volume (27 CFR 5.63(a)).', sev: 'error' },
    { id: 'name_address', msg: 'Importer name and address required for imported products (27 CFR 7.63(b)).', sev: 'error' },
    { id: 'net_contents', msg: 'Net contents must include US customary measure (27 CFR 7.70).', sev: 'error' },
  ],
  needs_revision: [
    { id: 'health_warning', msg: '"Government Warning:" must be in ALL CAPS per TTB regulations.', sev: 'error' },
    { id: 'sulfite_declaration', msg: 'Sulfite declaration required for wines containing ≥10 ppm SO₂ (27 CFR 4.32(e)).', sev: 'error' },
    { id: 'class_type', msg: 'Class/type on label does not match COLA application (27 CFR 5.55).', sev: 'warning' },
    { id: 'vintage_date', msg: 'Vintage date illegible or missing from front label.', sev: 'warning' },
  ],
};

let overrideLines = '';
for (let i = 0; i < total; i++) {
  const r = records[i];
  const status = shuffled[i];
  const brand = titleCase(r.brandName || '');
  const cat = r.category || 'spirits';
  const submitter = `${brand} ${submitterSuffixes[cat] || 'Beverage Co.'}`;
  const daysAgo = Math.floor(Math.random() * 12);
  const includeOcr = status !== 'submitted';
  const reviewer = reviewers[i % 2];

  overrideLines += `    // ${i}: ${brand} — ${status}\n`;

  if (status === 'submitted') {
    overrideLines += `    { status: "${status}", submitter: "${submitter}", daysAgo: ${daysAgo}, includeOcr: false },\n`;
  } else if (status === 'in_review') {
    overrideLines += `    { status: "${status}", submitter: "${submitter}", daysAgo: ${daysAgo}, includeOcr: true },\n`;
  } else if (status === 'approved') {
    overrideLines += `    {\n`;
    overrideLines += `      status: "${status}", submitter: "${submitter}", daysAgo: ${daysAgo}, includeOcr: true,\n`;
    overrideLines += `      review: {\n`;
    overrideLines += `        decision: "approve",\n`;
    overrideLines += `        reviewer: "${reviewer}",\n`;
    overrideLines += `        notes: "All mandatory fields present and compliant. Approved.",\n`;
    overrideLines += `        findings: [],\n`;
    overrideLines += `      },\n`;
    overrideLines += `    },\n`;
  } else if (status === 'rejected') {
    const f = findings.rejected[i % findings.rejected.length];
    overrideLines += `    {\n`;
    overrideLines += `      status: "${status}", submitter: "${submitter}", daysAgo: ${daysAgo}, includeOcr: true,\n`;
    overrideLines += `      review: {\n`;
    overrideLines += `        decision: "reject",\n`;
    overrideLines += `        reviewer: "${reviewer}",\n`;
    overrideLines += `        notes: "Label does not meet TTB requirements. See findings.",\n`;
    overrideLines += `        findings: [\n`;
    overrideLines += `          { checklistItemId: "${f.id}", severity: "${f.sev}", message: "${f.msg}" },\n`;
    overrideLines += `        ],\n`;
    overrideLines += `      },\n`;
    overrideLines += `    },\n`;
  } else {
    const f = findings.needs_revision[i % findings.needs_revision.length];
    overrideLines += `    {\n`;
    overrideLines += `      status: "${status}", submitter: "${submitter}", daysAgo: ${daysAgo}, includeOcr: true,\n`;
    overrideLines += `      review: {\n`;
    overrideLines += `        decision: "needs_revision",\n`;
    overrideLines += `        reviewer: "${reviewer}",\n`;
    overrideLines += `        notes: "Label requires corrections before approval. See findings.",\n`;
    overrideLines += `        findings: [\n`;
    overrideLines += `          { checklistItemId: "${f.id}", severity: "${f.sev}", message: "${f.msg}" },\n`;
    overrideLines += `        ],\n`;
    overrideLines += `      },\n`;
    overrideLines += `    },\n`;
  }
}

writeFileSync(join(ROOT, 'sample_labels', 'store_overrides_block.txt'), overrideLines);
console.log(`💾 Store overrides block saved to sample_labels/store_overrides_block.txt`);

console.log('\n✅ Done! Now update store.ts with the TTB_LABEL_IMAGES block and overrides.');
